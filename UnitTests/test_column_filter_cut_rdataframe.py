def collect_tests():
    tests = _case_tests()

    standalone = [
        test_single_dataframe_returns_single_dataframe,
        test_dataframe_list_returns_list,
        test_none_is_noop,
        test_blank_is_noop,
        test_empty_vector_mask_keeps_row,
        test_unreferenced_mismatched_vector_is_untouched,
        test_referenced_mismatched_vectors_fail_on_evaluation,
        test_multiple_cut_list_combines_into_one_mask,
        test_scalar_false_mixed_cut_keeps_row_with_empty_referenced_vectors,
        test_only_referenced_vector_columns_are_redefined,
    ]

    tests.extend((test.__name__, test) for test in standalone)

    assert len(tests) == 150, (
        f"Test suite must contain exactly 150 tests, got {len(tests)}."
    )
    return tests


def run_all_tests() -> int:
    tests = collect_tests()
    passed = 0
    failures = []

    print(
        f"Running {len(tests)} "
        "column_filter_cut_rdataframe tests...\n"
    )

    for index, (name, test) in enumerate(tests, start=1):
        try:
            test()
        except Exception as error:
            failures.append((name, error))
            print(
                f"[{index:03d}/{len(tests):03d}] "
                f"FAIL  {name}: "
                f"{type(error).__name__}: {error}"
            )
        else:
            passed += 1
            print(
                f"[{index:03d}/{len(tests):03d}] "
                f"PASS  {name}"
            )

    print("\n" + "=" * 72)
    print(f"Passed: {passed}")
    print(f"Failed: {len(failures)}")
    print(f"Total:  {len(tests)}")

    if failures:
        print("\nFailure details:")
        for name, error in failures:
            print(
                f"  - {name}: "
                f"{type(error).__name__}: {error}"
            )
        return 1

    print("\nAll tests passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(run_all_tests())