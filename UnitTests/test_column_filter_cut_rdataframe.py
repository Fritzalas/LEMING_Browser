def test_single_dataframe_returns_single_dataframe():
    dataframe = make_dataframe([{"X": [1, 2, 3], "Y": [4, 5, 6]}])
    result = column_filter_cut_rdataframe(dataframe, "X >= 2")
    assert not isinstance(result, list)
    assert materialize(result, ["X", "Y"]) == [
        {"X": [2, 3], "Y": [4, 5, 6]}
    ]


def test_dataframe_list_returns_list():
    first = make_dataframe([{"X": [1, 2, 3], "Y": [4, 5, 6]}])
    second = make_dataframe([{"X": [10, 20, 30], "Y": [1, 2, 3]}])
    result = column_filter_cut_rdataframe([first, second], "X > 2")

    assert isinstance(result, list)
    assert len(result) == 2
    assert materialize(result[0], ["X", "Y"]) == [
        {"X": [3], "Y": [4, 5, 6]}
    ]
    assert materialize(result[1], ["X", "Y"]) == [
        {"X": [10, 20, 30], "Y": [1, 2, 3]}
    ]


def test_none_is_noop():
    rows = [{"X": [1, 2], "Y": [3, 4], "Run": 1}]
    check_filter(rows, None, rows)


def test_blank_is_noop():
    rows = [{"X": [1, 2], "Y": [3, 4], "Run": 1}]
    check_filter(rows, "   ", rows)


def test_empty_vector_mask_keeps_row():
    rows = [{"X": [1, 2, 3], "Y": [10, 20, 30], "Run": 42}]
    check_filter(
        rows,
        "X > 100",
        [{"X": [], "Y": [10, 20, 30], "Run": 42}],
    )


def test_unreferenced_mismatched_vector_is_untouched():
    rows = [{
        "X": [1, 2, 3],
        "Short": [99],
        "Long": [5, 6, 7, 8, 9],
    }]
    check_filter(
        rows,
        "X >= 2",
        [{
            "X": [2, 3],
            "Short": [99],
            "Long": [5, 6, 7, 8, 9],
        }],
    )


def test_referenced_mismatched_vectors_fail_on_evaluation():
    dataframe = make_dataframe([{
        "X": [1, 2, 3],
        "Y": [10, 20],
        "Untouched": [7],
    }])

    result = column_filter_cut_rdataframe(
        dataframe,
        "X > 1 && Y > 1",
    )

    try:
        materialize(result, ["X", "Y", "Untouched"])
    except Exception:
        return

    raise AssertionError(
        "Expected referenced vector-length mismatch "
        "to fail during evaluation."
    )


def test_multiple_cut_list_combines_into_one_mask():
    rows = [{
        "X": [1, 2, 3, 4, 5],
        "Y": [5, 4, 3, 2, 1],
        "Good": [True, True, False, True, True],
        "Untouched": [100, 200, 300, 400, 500],
    }]
    check_filter(
        rows,
        ["X >= 2", "Y <= 4", "Good", "X + Y == 6"],
        [{
            "X": [2, 4, 5],
            "Y": [4, 2, 1],
            "Good": [True, True, True],
            "Untouched": [100, 200, 300, 400, 500],
        }],
    )


