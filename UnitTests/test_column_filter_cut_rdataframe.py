def _case_tests():
    tests = []
    for name, rows, cut, expected in CASES:
        def test(
            rows=rows,
            cut=cut,
            expected=expected,
        ):
            check_filter(rows, cut, expected)
        test.__name__ = f"test_{name}"
        tests.append((test.__name__, test))
    return tests


